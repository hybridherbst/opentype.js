import assert from 'assert';
import { Font, Glyph, Path } from '../src/opentype.js';
import { VariationManager } from '../src/variation.js';

describe('variation intermediate tuples', function() {
    it('preserves intermediate tuple regions for gvar and HVAR generated by addAxis', function() {
        const basePath = new Path();
        basePath.moveTo(0, 0);
        basePath.lineTo(100, 0);
        basePath.lineTo(100, 100);
        basePath.lineTo(0, 100);
        basePath.closePath();

        const font = new Font({
            familyName: 'Test',
            styleName: 'Regular',
            unitsPerEm: 1000,
            ascender: 800,
            descender: -200,
            glyphs: [
                new Glyph({ name: '.notdef', unicode: 0, advanceWidth: 500, path: new Path() }),
                new Glyph({ name: 'A', unicode: 65, advanceWidth: 500, path: basePath })
            ]
        });

        font.variation = new VariationManager(font);
        font.variation.addAxis({
            tag: 'wght',
            name: 'Weight',
            minValue: 100,
            defaultValue: 400,
            maxValue: 900,
            deltaGenerator: (glyph) => {
                if (glyph.name !== 'A') return null;
                const zeroPointDeltas = [0, 0, 0, 0, 0, 0, 0, 0];
                return [
                    {
                        peakTuple: [-1],
                        deltas: zeroPointDeltas,
                        deltasY: zeroPointDeltas,
                        advanceWidthDelta: 120
                    },
                    {
                        peakTuple: [-1 / 3],
                        intermediateStartTuple: [-1],
                        intermediateEndTuple: [0],
                        deltas: zeroPointDeltas,
                        deltasY: zeroPointDeltas,
                        advanceWidthDelta: -50
                    }
                ];
            }
        });

        const headers = font.tables.gvar.glyphVariations[1].headers;
        const intermediateHeader = headers.find(header => header.intermediateStartTuple);
        assert.ok(intermediateHeader, 'gvar should keep intermediate tuple support');
        assert.deepEqual(intermediateHeader.intermediateStartTuple, [-1]);
        assert.deepEqual(intermediateHeader.intermediateEndTuple, [0]);

        const hvarRegions = font.tables.hvar.itemVariationStore.variationRegions;
        const intermediateRegion = hvarRegions.find(region => Math.abs(region.regionAxes[0].peakCoord + 1 / 3) < 0.0001);
        assert.ok(intermediateRegion, 'HVAR should keep the intermediate tuple as its own region');
        assert.equal(intermediateRegion.regionAxes[0].startCoord, -1);
        assert.equal(intermediateRegion.regionAxes[0].endCoord, 0);
    });
});
